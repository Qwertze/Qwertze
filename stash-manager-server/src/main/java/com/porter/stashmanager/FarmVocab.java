package com.porter.stashmanager;

import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.regex.Pattern;

/**
 * The closed vocabularies and patterns of FARM-CONTRACT v1.0 and TASK-CONTRACT v1.0 (slice). Everything a bot may say in a
 * farm report is one of these; anything else is a 400 that never repeats the value.
 */
final class FarmVocab {
    private FarmVocab() {
    }

    static final Pattern BOT_ID = Pattern.compile("^[A-Za-z0-9_-]{1,64}$");
    static final Pattern TASK_ID = Pattern.compile("^t-[0-9a-f]{12}$");
    static final Pattern FARM_ID = Pattern.compile("^f-[0-9a-f]{8}$");
    static final Pattern HASH = Pattern.compile("^[0-9a-f]{64}$");
    static final Pattern NAMESPACED = Pattern.compile("^[a-z0-9_.-]+:[a-z0-9_./-]+$");
    static final Pattern ITEM_KEY = Pattern.compile("^[a-z0-9_.-]+:[a-z0-9_./-]+$");
    static final Pattern STATION_ID = Pattern.compile("^ps-[0-9a-f]{8}$");
    static final Pattern PLAYER = Pattern.compile("^[A-Za-z0-9_]{1,16}$");
    /** a0 to a63 (FARM A2: at most 64 anchors). */
    static final Pattern ANCHOR_ID = Pattern.compile("^a([0-9]|[1-5][0-9]|6[0-3])$");
    static final Pattern VERSION = Pattern.compile("^[0-9A-Za-z._+-]{1,32}$");

    static final int MAX_INT = Integer.MAX_VALUE;
    static final int MAX_ID_LEN = 64;

    /** The roles the owner may give (closed in M2). */
    static final List<String> ROLES = List.of("farmer", "loader");

    static final String KIND_FARM = "farm.session";
    static final String FARM_TITLE = "Farm session";

    /** FARM A6: every mode a program can be recorded for. */
    static final List<String> MODES = List.of("afk_still", "custom", "afk_swing", "afk_use", "hold_use", "fishing", "raid",
        "gold_iron", "wither_shulker", "trading", "crop_replant");
    /** What M2 runs. Any other mode is refused at start with mode_not_ready (draft 2.3). */
    static final Set<String> M2_MODES = Set.of("custom", "afk_still");

    /** Closed phases of a farm session (report phase and sync running.phase). */
    static final Set<String> PHASES = Set.of("setup", "loop", "recover", "stop_steps", "parked", "waiting");
    static final Set<String> CHECKPOINT_STEPS = Set.of("setup", "loop", "recover", "stop_steps", "parked");

    /** E3: park codes (task state paused). */
    static final Set<String> PARK_CODES = Set.of("controller_connected", "disconnected", "pathfinder_busy", "server_unreachable", "lease_lost");
    /** E3: codes that end the task cancelled. */
    static final Set<String> CANCEL_CODES = Set.of("stopped", "ops_stop", "pause_timeout", "offer_timeout", "role_removed");
    /** E3: codes that end the task failed. */
    static final Set<String> FAIL_CODES = Set.of("player_near", "low_health", "no_food", "no_totem", "drifted", "farm_changed",
        "inventory_full", "item_missing", "not_at_farm", "wrong_dim", "chunk_not_loaded", "module_conflict", "guard_off",
        "unsafe_logging", "unsafe_discord", "unsafe_bridge", "unsafe_rotation", "unsafe_viewer", "key_missing", "key_mismatch", "key_invalid",
        "key_perms", "mode_not_ready", "program_missing", "program_mismatch", "error");
    /** E3: the one code of a normal end. */
    static final String COMPLETED_CODE = "time_up";
    /** Every code a farm report may carry: the three tables above plus time_up. */
    static final Set<String> ALL_CODES;

    /** The words the owner sees for each code (generated by the server; a bot's own text is never stored). */
    static final Map<String, String> TEXT = new LinkedHashMap<>();

    static {
        java.util.HashSet<String> all = new java.util.HashSet<>();
        all.addAll(PARK_CODES);
        all.addAll(CANCEL_CODES);
        all.addAll(FAIL_CODES);
        all.add(COMPLETED_CODE);
        ALL_CODES = Set.copyOf(all);
        for (String c : ALL_CODES) TEXT.put(c, "stopped (" + c + ")");
        TEXT.put("time_up", "Ran for the time limit");
        TEXT.put("stopped", "Stopped by the owner");
        TEXT.put("ops_stop", "Emergency stop");
        TEXT.put("pause_timeout", "Paused for too long");
        TEXT.put("offer_timeout", "The farmer did not pick the session up in time");
        TEXT.put("role_removed", "The farmer role was taken away");
        TEXT.put("lease_lost", "Lost contact with the server");
        TEXT.put("player_near", "A player came too close");
        TEXT.put("low_health", "Health got too low");
        TEXT.put("no_food", "Out of food");
        TEXT.put("no_totem", "No totem in the off hand");
        TEXT.put("drifted", "Drifted off the route and could not recover");
        TEXT.put("mode_not_ready", "This mode is not ready yet");
        TEXT.put("program_missing", "The farmer has no program for this farm");
        TEXT.put("program_mismatch", "The farmer's program differs from the farm's");
        TEXT.put("controller_connected", "Paused: a player is connected");
        TEXT.put("disconnected", "Paused: the bot is disconnected");
        TEXT.put("server_unreachable", "Paused: the manager server was unreachable");
    }

    /** The server's own text for a code. */
    static String text(String code) {
        return code == null ? null : TEXT.getOrDefault(code, "stopped (" + code + ")");
    }

    /** Checkpoint data keys and their ranges. */
    static final Map<String, Long> DATA_MAX = Map.of("loop", 1_000_000L, "tick", 72_000L, "recoveries", 1_000L);
}
